//! Step 1: one role grants one action on one exact article.

// These are the four pieces used throughout this tutorial:
//
// - `Policy` stores the rules for what each role is allowed to do.
// - `Access` stores the roles the application has established for one caller.
// - `Authorizer` evaluates an access value against a policy.
// - `TargetType` provides typed identities such as `Article::ident(1)`.
//
// `define_authorization` is the macro that creates the target and action types
// used by all of those pieces.
use rust_but_verify::{Access, Authorizer, Policy, TargetType, define_authorization};

// Define the vocabulary for this application's authorization model.
// The macro creates Rust types at compile time. Later, the policy rules that use
// those types may be assembled statically or from data your application loads.
define_authorization! {
    // A target is the kind of resource someone wants to act on.
    // Our first model contains only one kind of target: an article.
    //
    // `Article` is the Rust type generated by the macro. `"article"` is its
    // stable name in the authorization model.
    target Article = "article" {
        // An action is something a caller may ask to do to this target.
        // This use case needs only one action: editing an article.
        //
        // `EditArticle` becomes the typed Rust value used below, while
        // `"article.edit"` is the stable name you chose for the action.
        action EditArticle = "article.edit";
    };
}

fn main() -> Result<(), rust_but_verify::PolicyError> {
    // A policy answers: "What is a role allowed to do?"
    // It does not answer: "Who has that role, and on which exact resource?"
    // The application supplies that second piece later through `Access`.
    let mut policy_builder = Policy::builder();

    // Add one rule: the role named `article_editor` allows the `EditArticle`
    // action. Role names are application-defined strings, just like the target
    // and action names above.
    policy_builder.allow("article_editor", EditArticle);

    // Finish and validate the policy. `build` can fail when a policy is invalid,
    // which is why `main` returns `PolicyError` and uses `?` here.
    let authorization_policy = policy_builder.build()?;

    // The authorizer holds the completed policy and will use it to answer
    // authorization questions. It does not load users, roles, or articles.
    let authorizer = Authorizer::new(authorization_policy);

    // Imagine the application has authenticated Bob and established that he is
    // an editor of Article 1. Turn that trusted application fact into `Access`.
    //
    // Access always connects a role to an exact target. Bob receives
    // `article_editor` on Article 1, not a global `article_editor` role.
    // `Article::ident(1)` keeps the resource kind attached to its ID, so an
    // article ID cannot be accidentally confused with another kind of ID.
    let access_given_to_bob = Access::with_role("article_editor", Article::ident(1));

    // Now ask the complete authorization question:
    //
    // "Given Bob's access, may he perform `EditArticle` on Article 1?"
    //
    // `can` returns a boolean. This is true because all three parts line up:
    // Bob has the role, the policy allows that role to edit, and the role was
    // granted on the same exact Article target being checked.
    let can_bob_edit_article_1 =
        authorizer.can(&access_given_to_bob, EditArticle, Article::ident(1));

    // Ask the same question about Article 2. The policy rule still matches, but
    // Bob's access does not: his role was granted only on Article 1. Therefore
    // this check is false. Access to one target does not leak to another target.
    let can_bob_edit_article_2 =
        authorizer.can(&access_given_to_bob, EditArticle, Article::ident(2));

    // In a real application, these booleans could decide whether to continue a
    // request or return an authorization error. We print and assert them so this
    // executable example documents its expected behavior.
    println!("Can Bob edit article 1? {can_bob_edit_article_1}");
    println!("Can Bob edit article 2? {can_bob_edit_article_2}");

    assert!(can_bob_edit_article_1);
    assert!(!can_bob_edit_article_2);
    Ok(())
}
